/**
 * Generates tiny base64-encoded blur placeholders for every local image
 * referenced by public/images/*, so next/image can show a blurred preview
 * instead of a blank flash while the full photo loads — especially useful
 * on the slow mobile connections most guests will open this on from WhatsApp.
 *
 * Run manually whenever images change:
 *   node scripts/generate-blur-placeholders.mjs
 *
 * Output: src/data/blur-placeholders.ts (committed to git, not regenerated at
 * request time — this keeps the guest-facing pages free of any per-request
 * image processing cost).
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const IMAGES_DIR = path.join(process.cwd(), "public", "images");
const OUTPUT_FILE = path.join(process.cwd(), "src", "data", "blur-placeholders.ts");

async function main() {
  const files = (await readdir(IMAGES_DIR)).filter((f) =>
    /\.(jpe?g|png|webp)$/i.test(f)
  );

  const entries = await Promise.all(
    files.map(async (file) => {
      const fullPath = path.join(IMAGES_DIR, file);
      // Shrink to a ~12px-wide buffer — small enough to inline as base64
      // without bloating the HTML, blurry enough that next/image's blur
      // filter smooths out any block artifacts.
      const buffer = await sharp(fullPath)
        .resize(12)
        .jpeg({ quality: 40 })
        .toBuffer();

      const dataUrl = `data:image/jpeg;base64,${buffer.toString("base64")}`;
      return [`/images/${file}`, dataUrl];
    })
  );

  const map = Object.fromEntries(entries);

  const fileContents = `// AUTO-GENERATED by scripts/generate-blur-placeholders.mjs — do not edit by hand.
// Re-run the script after adding/replacing images in public/images.

export const blurPlaceholders: Record<string, string> = ${JSON.stringify(
    map,
    null,
    2
  )};

/** Returns the blurDataURL for a local image path, or undefined if not found. */
export function getBlurDataURL(src: string): string | undefined {
  return blurPlaceholders[src];
}
`;

  await writeFile(OUTPUT_FILE, fileContents, "utf-8");
  console.log(`✓ Generated blur placeholders for ${files.length} images → ${OUTPUT_FILE}`);
}

main().catch((err) => {
  console.error("Failed to generate blur placeholders:", err);
  process.exit(1);
});
